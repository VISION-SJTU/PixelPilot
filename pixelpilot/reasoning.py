"""Generate resumable reasoning candidates using the recovered teacher prompt."""

import argparse
import base64
import io
import json
import os
from pathlib import Path
import re

from .data.reasoning_prompt import PROMPT_FORMAT
from .formats import extract_tag
from .io import image_path, read_records, validate_annotations
from .prepare import validate_targets


def prompt_for(row):
    target = row["messages"][1]["content"]
    speed = re.search(r"Speed: (\d+\.?\d*)", row["messages"][0]["content"])
    return PROMPT_FORMAT.format(speed=speed.group(1) if speed else "unknown",
                                perception=extract_tag(target, "perception"), action=extract_tag(target, "action"))


def read_candidates(path):
    records = read_records(path)
    result = {}
    for row in records:
        token, reason = row.get("id"), row.get("reasoning")
        if not isinstance(token, str) or token in result or not isinstance(reason, str) or not reason.strip():
            raise ValueError("Reasoning candidates need unique ids and non-empty text")
        if re.search(r"</?(?:think|action|answer|perception)>", reason):
            raise ValueError(f"{token}: reasoning must be plain text without output control tags")
        result[token] = row
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--annotations", required=True, help="Unique integrated records, usually training failure cases")
    parser.add_argument("--image-root", required=True)
    parser.add_argument("--model", required=True, help="Explicit teacher model id; historical script used qwen-vl-max-latest")
    parser.add_argument("--base-url", default="https://dashscope.aliyuncs.com/compatible-mode/v1")
    parser.add_argument("--output", required=True)
    parser.add_argument("--limit", type=int)
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--dry-run", action="store_true", help="Preview the prompt and count without images, API calls or output files")
    args = parser.parse_args()
    rows = read_records(args.annotations)
    if args.limit is not None:
        if args.limit < 1:
            parser.error("--limit must be positive")
        rows = rows[:args.limit]
    validate_annotations(rows)
    validate_targets(rows)
    if args.dry_run:
        print(json.dumps({"samples": len(rows), "model": args.model, "base_url": args.base_url,
                          "first_prompt": prompt_for(rows[0]), "api_calls": 0}, indent=2))
        return
    output = Path(args.output)
    previous = read_candidates(output) if args.resume and output.exists() and output.stat().st_size else {}
    if any(row.get("model") != args.model for row in previous.values()):
        raise ValueError("Cannot resume candidates generated by a different teacher model")
    if set(previous) - {row["id"] for row in rows}:
        raise ValueError("Resume output contains ids outside the requested annotation subset")
    if output.exists() and not args.resume:
        raise FileExistsError(output)
    key = os.environ.get("DASHSCOPE_API_KEY")
    if not key:
        raise RuntimeError("Set DASHSCOPE_API_KEY before explicitly requesting candidate generation")
    validate_annotations(rows, args.image_root)
    from openai import OpenAI
    from PIL import Image

    client = OpenAI(api_key=key, base_url=args.base_url, timeout=120.0, max_retries=2)
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("a" if args.resume else "x", encoding="utf-8") as stream:
        for row in rows:
            if row["id"] in previous:
                continue
            with Image.open(image_path(args.image_root, row["images"][0])) as image:
                buffer = io.BytesIO()
                image.convert("RGB").save(buffer, format="JPEG")
            url = "data:image/jpeg;base64," + base64.b64encode(buffer.getvalue()).decode()
            response = client.chat.completions.create(model=args.model, temperature=0.2, max_tokens=8192, messages=[{
                "role": "user", "content": [
                    {"type": "image_url", "image_url": {"url": url}}, {"type": "text", "text": prompt_for(row)},
                ],
            }])
            reasoning = response.choices[0].message.content
            if not isinstance(reasoning, str) or not reasoning.strip() or re.search(r"</?(?:think|action|answer|perception)>", reasoning):
                raise ValueError(f"{row['id']}: invalid teacher output; previous results are retained for resume")
            stream.write(json.dumps({"id": row["id"], "reasoning": reasoning, "model": args.model, "status": "candidate"}, ensure_ascii=False) + "\n")
            stream.flush()


if __name__ == "__main__":
    main()
